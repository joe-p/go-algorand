//! ARC-4 routing generated by `#[contract]` on an impl with `#[abimethod]`s.
//!
//! The expected selectors were computed independently, as the first 4 bytes of
//! SHA-512/256 of each signature.

mod common;

use avm_sdk::arc4::{Address, Arc4Contract};
use avm_sdk::testing::set_host;
use avm_sdk::{contract, Error, GlobalBytes, GlobalUint};
use common::{CallAvm, OPT_IN};

#[contract]
pub struct Registry {
    owner: GlobalBytes,
    count: GlobalUint,
    label: GlobalBytes,
}

#[contract]
impl Registry {
    #[abimethod(create)]
    pub fn init(&self, owner: Address) {
        self.owner.write(&owner.0);
    }

    #[abimethod]
    pub fn increment(&self, delta: u64) -> Result<(), Error> {
        if delta == 0 {
            return Err(Error::InvalidValue);
        }
        self.count.set(self.count.get() + delta);
        Ok(())
    }

    #[abimethod]
    pub fn set_label(&self, label: &str) {
        self.label.write(label.as_bytes());
    }

    #[abimethod]
    pub fn check(&self, flag: bool, small: u8, tag: [u8; 4], data: &[u8]) -> Result<(), Error> {
        if flag && small == 7 && tag == *b"abcd" && data == b"xyz" {
            Ok(())
        } else {
            Err(Error::InvalidValue)
        }
    }

    #[abimethod(name = "ping")]
    pub fn health(&self) {}
}

const INIT: [u8; 4] = [0xf4, 0x70, 0x06, 0x61];
const INCREMENT: [u8; 4] = [0x82, 0x96, 0xda, 0x2e];
const SET_LABEL: [u8; 4] = [0x4d, 0x7b, 0x54, 0xb8];
const CHECK: [u8; 4] = [0xba, 0xe3, 0x37, 0x53];
const PING: [u8; 4] = [0x18, 0x8b, 0x8f, 0xb4];

/// ABI-encodes a dynamic `byte[]` / `string`.
fn dynamic(bytes: &[u8]) -> Vec<u8> {
    let mut out = (bytes.len() as u16).to_be_bytes().to_vec();
    out.extend_from_slice(bytes);
    out
}

#[test]
fn metadata_matches_reference_selectors() {
    let methods: Vec<_> = Registry::METHODS
        .iter()
        .map(|m| (m.signature, m.selector, m.create))
        .collect();
    assert_eq!(
        methods,
        [
            ("init(address)void", INIT, true),
            ("increment(uint64)void", INCREMENT, false),
            ("set_label(string)void", SET_LABEL, false),
            ("check(bool,uint8,byte[4],byte[])void", CHECK, false),
            ("ping()void", PING, false),
        ]
    );
    let check = &Registry::METHODS[3];
    let args: Vec<_> = check.args.iter().map(|a| (a.name, a.ty)).collect();
    assert_eq!(
        args,
        [
            ("flag", "bool"),
            ("small", "uint8"),
            ("tag", "byte[4]"),
            ("data", "byte[]")
        ]
    );
    assert_eq!(Registry::METHODS[4].name, "ping");
}

#[test]
fn create_method_runs_only_at_creation() {
    let host = set_host(CallAvm::create(&[&INIT, &[0x11; 32]]));
    assert_eq!(program(), 1);
    assert_eq!(host.bytes(b"owner"), Some(vec![0x11; 32]));
    drop(host);

    let _host = set_host(CallAvm::call(&[&INIT, &[0x11; 32]]));
    assert_eq!(program(), 0);
}

#[test]
fn call_methods_reject_at_creation() {
    let _host = set_host(CallAvm::create(&[&INCREMENT, &5u64.to_be_bytes()]));
    assert_eq!(program(), 0);
}

#[test]
fn increment_decodes_uint64() {
    let host = set_host(CallAvm::call(&[&INCREMENT, &5u64.to_be_bytes()]));
    assert_eq!(program(), 1);
    assert_eq!(program(), 1);
    assert_eq!(host.uint(b"count"), Some(10));
}

#[test]
fn method_errors_reject() {
    let _host = set_host(CallAvm::call(&[&INCREMENT, &0u64.to_be_bytes()]));
    assert_eq!(program(), 0);
}

#[test]
fn malformed_arguments_reject() {
    for args in [
        // Too few, too many, and wrong-length arguments.
        vec![INCREMENT.to_vec()],
        vec![INCREMENT.to_vec(), 5u64.to_be_bytes().to_vec(), vec![0]],
        vec![INCREMENT.to_vec(), vec![0; 7]],
        // A length prefix that does not match the payload.
        vec![SET_LABEL.to_vec(), vec![0, 5, b'a']],
        // Invalid UTF-8 in a string.
        vec![SET_LABEL.to_vec(), dynamic(&[0xff])],
        // A bool other than 0x00 / 0x80.
        vec![
            CHECK.to_vec(),
            vec![0x01],
            vec![7],
            b"abcd".to_vec(),
            dynamic(b"xyz"),
        ],
    ] {
        let args: Vec<&[u8]> = args.iter().map(Vec::as_slice).collect();
        let _host = set_host(CallAvm::call(&args));
        assert_eq!(program(), 0, "args {args:?}");
    }
}

#[test]
fn dynamic_and_static_types_decode() {
    let host = set_host(CallAvm::call(&[&SET_LABEL, &dynamic(b"hello")]));
    assert_eq!(program(), 1);
    assert_eq!(host.bytes(b"label"), Some(b"hello".to_vec()));
    drop(host);

    let _host = set_host(CallAvm::call(&[
        &CHECK,
        &[0x80],
        &[7],
        b"abcd",
        &dynamic(b"xyz"),
    ]));
    assert_eq!(program(), 1);
}

#[test]
fn name_override_sets_the_selector() {
    let _host = set_host(CallAvm::call(&[&PING]));
    assert_eq!(program(), 1);
}

#[test]
fn unknown_or_short_selectors_reject() {
    for selector in [
        &[0xde, 0xad, 0xbe, 0xef][..],
        &PING[..3],
        &[PING, PING].concat(),
    ] {
        let _host = set_host(CallAvm::call(&[selector]));
        assert_eq!(program(), 0, "selector {selector:?}");
    }
}

#[test]
fn methods_require_no_op() {
    let mut avm = CallAvm::call(&[&PING]);
    avm.on_completion = OPT_IN;
    let _host = set_host(avm);
    assert_eq!(program(), 0);
}

#[test]
fn bare_create_is_allowed_without_approve() {
    let host = set_host(CallAvm::create(&[]));
    assert_eq!(program(), 1);
    drop(host);

    // A bare call on an existing app, or a bare create that is not NoOp, is not.
    let host = set_host(CallAvm::call(&[]));
    assert_eq!(program(), 0);
    drop(host);
    let mut avm = CallAvm::create(&[]);
    avm.on_completion = OPT_IN;
    let _host = set_host(avm);
    assert_eq!(program(), 0);
}
